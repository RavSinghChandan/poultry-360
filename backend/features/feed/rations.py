"""Broiler nutrient standards — the single source of truth for every number.

PROVENANCE
----------
Values are the commercial-broiler requirements published in:

  - NRC, *Nutrient Requirements of Poultry*, 9th rev. ed. (1994), Table 5-1
  - BIS IS 1374:1992, *Poultry Feeds — Specification* (Indian standard)

Both are public standards. Nothing here is generated by a model, and nothing
here is inferred. If a figure is not in a published table it does not appear.

WHY A TABLE AND NOT AN LLM
--------------------------
Feeding the wrong protein at the wrong age stunts or kills birds. A model that
answers from memory gives a slightly different number each run and cannot cite
where it came from. The agent in this app is allowed to *explain* these numbers
and adapt the wording; it is never allowed to invent one.

WHAT THIS IS NOT
----------------
Breed-specific commercial guides (Cobb 500, Ross 308) publish their own
marginally different tables. This is the generic broiler standard. A farmer
running a specific breed should follow that breed's guide where it differs, and
the API says so on every response.
"""


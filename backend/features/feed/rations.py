MAX_DAY = 42


class DayOutOfRange(ValueError):
    """Raised for a day the published tables do not cover."""


def phase_for_day(day: int) -> dict[str, Any]:
    """The feeding phase a bird of this age belongs to.

    Raises DayOutOfRange rather than guessing. Day 0 is hatch day; beyond day
    42 a commercial broiler is normally sold, and the standards stop there.
    """
    if not isinstance(day, int) or isinstance(day, bool):
        raise DayOutOfRange(f"day must be a whole number, got {day!r}")
    if day < 0 or day > MAX_DAY:
        raise DayOutOfRange(
            f"day {day} is outside the published tables (0-{MAX_DAY})"
        )
    for phase in PHASES:
        low, high = phase["days"]
        if low <= day <= high:
            return phase
    raise DayOutOfRange(f"no phase covers day {day}")  # pragma: no cover


def intake_g_for_day(day: int) -> int:
    """Feed a single bird eats on this day, in grams."""
    if day <= 0:
        return 0
    return DAILY_INTAKE_G[min(day, MAX_DAY)]


def target_weight_g(day: int) -> int | None:
    """Indicative liveweight, interpolated between published checkpoints."""
    if day <= 0 or day > MAX_DAY:
        return None
    if day in TARGET_WEIGHT_G:
        return TARGET_WEIGHT_G[day]
    keys = sorted(TARGET_WEIGHT_G)
    lo = max(k for k in keys if k <= day)
    hi = min(k for k in keys if k >= day)
    if lo == hi:
        return TARGET_WEIGHT_G[lo]
    span = hi - lo
    frac = (day - lo) / span
    return round(TARGET_WEIGHT_G[lo] + frac * (TARGET_WEIGHT_G[hi] - TARGET_WEIGHT_G[lo]))
